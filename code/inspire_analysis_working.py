# ---------- standardized mean differences (balance) ----------
d["asa3"]=(d["asa_cat"]=="3+").astype(int); d["knee"]=(d["proc"]=="knee").astype(int)
def smd(df,var,w=None):
    t=df[df.neuraxial==1]; c=df[df.neuraxial==0]
    if w is None:
        mt,mc=t[var].mean(),c[var].mean(); vt,vc=t[var].var(),c[var].var()
    else:
        wt,wc=w[df.neuraxial==1],w[df.neuraxial==0]
        mt=np.average(t[var],weights=wt); mc=np.average(c[var],weights=wc)
        vt=np.average((t[var]-mt)**2,weights=wt); vc=np.average((c[var]-mc)**2,weights=wc)
    return (mt-mc)/np.sqrt((vt+vc)/2+1e-9)

# ---------- propensity score + stabilized IPTW ----------
ps_m = smf.logit("neuraxial ~ age + female + C(asa_cat) + emop + C(proc)",
                 data=d).fit(disp=False)
d["ps"] = ps_m.predict(d)
p_treat = d["neuraxial"].mean()
d["iptw"] = np.where(d.neuraxial==1, p_treat/d.ps, (1-p_treat)/(1-d.ps))
cap = d["iptw"].quantile(0.99); d["iptw"] = d["iptw"].clip(upper=cap)  # trim extremes

print("\nBalance (standardized mean difference; <0.1 = well balanced):")
print(f"{'covariate':10s} {'before':>8s} {'after':>8s}")
for v in ["age","female","asa3","emop","knee"]:
    print(f"{v:10s} {smd(d,v):+8.3f} {smd(d,v,d['iptw']):+8.3f}")

