# ---- arthroplasty ICD-10-PCS codes (hip + knee replacement) ----
ARTHRO_CODES = ["0SRC","0SRD","0SR9","0SRB","0SRA","0SRE"]

def run_cohort(df, label):
    print("="*64); print("COHORT:", label)
    df = df.copy()
    # outcomes
    df["los_days"] = (df["discharge_time"] - df["admission_time"])/(60*24)
    df = df[(df["los_days"] > 0) & (df["los_days"] < 365)]      # drop impossible LOS
    df["los_days"] = df["los_days"].clip(lower=0.5)              # Gamma needs strictly >0
    df["icu_admit"] = df["icuin_time"].notna().astype(int)
    # exposure + covariates
    df["neuraxial"] = (df["antype"]=="Neuraxial").astype(int)
    df["female"] = (df["sex"]=="F").astype(int)
    def asa_cat(x):
        if pd.isna(x): return np.nan
        return "1-2" if x<=2 else "3+"
    df["asa_cat"] = df["asa"].apply(asa_cat)
    def pg(c):
        c=str(c)
        if c[:4] in ("0SRC","0SRD"): return "knee"
        if c[:4] in ("0SR9","0SRB","0SRA","0SRE"): return "hip"
        if c[:3]=="0SG": return "spine"
        return "other"
    df["proc"] = df["icd10_pcs"].apply(pg)

    d = df.dropna(subset=["los_days","neuraxial","age","female","asa_cat","emop"]).copy()
    print(f"complete-case n: {len(d):,}  (dropped {len(df)-len(d)} for missing covariates)")

    # descriptive: LOS & ICU by anesthesia
    print("\nLOS (days) by anesthesia:")
    print(d.groupby("antype")["los_days"].agg(["count","mean","median"]).round(2).to_string())
    print("\nICU admission rate by anesthesia:")
    print(d.groupby("antype")["icu_admit"].mean().round(3).to_string())

    def tbl(m):
        ci=m.conf_int()
        return pd.DataFrame({"est":np.exp(m.params),"low":np.exp(ci[0]),
                             "high":np.exp(ci[1]),"p":m.pvalues}).round(3)

    # For arthroplasty, proc has only hip/knee; for all-ortho it has 4 levels
    proc_term = "C(proc)" if d["proc"].nunique() > 1 else ""
    rhs = "neuraxial + age + female + C(asa_cat) + emop" + (" + "+proc_term if proc_term else "")

    print("\nPRIMARY  LOS  (Gamma, log link) -> est = RATIO OF MEAN LOS:")
    m1 = smf.glm(f"los_days ~ {rhs}", data=d,
                 family=sm.families.Gamma(link=sm.families.links.Log())).fit()
    print(tbl(m1).to_string())

    print("\nSECONDARY  ICU admission  (logistic) -> est = ODDS RATIO:")
    m2 = smf.logit(f"icu_admit ~ {rhs}", data=d).fit(disp=False)
    print(tbl(m2).to_string())
    return d, m1, m2

